function generateDetailedInsights(data: ProcessedData): string {
  const { summary, rows, headers } = data;
  let insights = '';

  // Overall data characteristics
  insights += 'Dataset Characteristics:\n';
  insights += `• Dataset Size: ${rows.length > 10000 ? 'Large' : rows.length > 1000 ? 'Medium' : 'Small'} dataset with ${rows.length.toLocaleString()} records\n`;
  insights += `• Data Complexity: ${headers.length > 20 ? 'High' : headers.length > 10 ? 'Medium' : 'Low'} complexity with ${headers.length} attributes\n`;
  
  const numRatio = summary.numericalColumns.length / headers.length;
  if (numRatio > 0.7) {
    insights += '• Data Type: Predominantly numerical data - well-suited for statistical analysis and machine learning\n';
  } else if (numRatio > 0.3) {
    insights += '• Data Type: Mixed data types - good balance for comprehensive analysis\n';
  } else {
    insights += '• Data Type: Predominantly categorical data - ideal for classification and pattern analysis\n';
  }

  // Numerical insights
  if (summary.numericalColumns.length > 0) {
    insights += '\nNumerical Data Analysis:\n';
    
    summary.numericalColumns.forEach(column => {
      const stats = summary.columnStats[column];
      if (stats.mean && stats.stdDev && stats.min !== undefined && stats.max !== undefined) {
        const range = stats.max - stats.min;
        const cv = (stats.stdDev / stats.mean) * 100;
        
        insights += `• ${column}:\n`;
        insights += `  - Range: ${range.toFixed(2)} (${stats.min} to ${stats.max})\n`;
        insights += `  - Average: ${stats.mean.toFixed(2)}\n`;
        insights += `  - Variability: ${cv < 15 ? 'Low' : cv < 30 ? 'Moderate' : 'High'} (CV: ${cv.toFixed(1)}%)\n`;
        
        if (stats.mean > (stats.min + stats.max) / 2) {
          insights += `  - Distribution: Data tends toward higher values\n`;
        } else if (stats.mean < (stats.min + stats.max) / 2) {
          insights += `  - Distribution: Data tends toward lower values\n`;
        } else {
          insights += `  - Distribution: Data is fairly centered\n`;
        }
      }
    });
  }

  // Categorical insights
  if (summary.categoricalColumns.length > 0) {
    insights += '\nCategorical Data Analysis:\n';
    
    summary.categoricalColumns.forEach(column => {
      const stats = summary.columnStats[column];
      if (stats.uniqueValues && stats.totalCount && stats.mostCommon) {
        const diversity = (stats.uniqueValues / stats.totalCount) * 100;
        const topCategory = stats.mostCommon[0];
        
        insights += `• ${column}:\n`;
        insights += `  - Categories: ${stats.uniqueValues} unique values\n`;
        insights += `  - Diversity: ${diversity < 10 ? 'Low' : diversity < 50 ? 'Moderate' : 'High'} (${diversity.toFixed(1)}%)\n`;
        insights += `  - Dominant Category: "${topCategory.value}" (${topCategory.percentage.toFixed(1)}% of data)\n`;
        
        if (topCategory.percentage > 70) {
          insights += `  - Distribution: Highly skewed toward "${topCategory.value}"\n`;
        } else if (topCategory.percentage > 40) {
          insights += `  - Distribution: Moderately concentrated\n`;
        } else {
          insights += `  - Distribution: Well distributed across categories\n`;
        }
      }
    });
  }

  return insights;
}

