function generateFallbackInsights(data: ProcessedData): string {
  const { summary } = data;
  let insights = '';
  
  insights += 'BASIC DATA ANALYSIS:\n\n';
  
  insights += '• Dataset Characteristics:\n';
  insights += `  - Size: ${summary.rowCount.toLocaleString()} records across ${summary.columnCount} columns\n`;
  insights += `  - Data Mix: ${summary.numericalColumns.length} numerical, ${summary.categoricalColumns.length} categorical columns\n\n`;
  
  if (summary.numericalColumns.length > 0) {
    insights += '• Numerical Data Insights:\n';
    summary.numericalColumns.forEach(col => {
      const stats = summary.columnStats[col] as any;
      if (stats.mean !== undefined) {
        insights += `  - ${col}: Average ${stats.mean.toFixed(2)}, Range ${stats.min} to ${stats.max}\n`;
      }
    });
    insights += '\n';
  }
  
  if (summary.categoricalColumns.length > 0) {
    insights += '• Categorical Data Insights:\n';
    summary.categoricalColumns.forEach(col => {
      const stats = summary.columnStats[col] as any;
      if (stats.uniqueValues) {
        insights += `  - ${col}: ${stats.uniqueValues} unique categories\n`;
      }
    });
  }
  
  return insights;
} 