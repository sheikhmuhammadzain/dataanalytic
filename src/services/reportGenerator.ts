function analyzeDataQuality(data: ProcessedData): string {
  const { rows, headers } = data;
  let qualityReport = '';

  // Check for missing values
  const missingValueCounts: Record<string, number> = {};
  headers.forEach(header => {
    missingValueCounts[header] = rows.filter(row => 
      row[header] === null || row[header] === undefined || row[header] === ''
    ).length;
  });

  qualityReport += 'Missing Values Analysis:\n';
  Object.entries(missingValueCounts).forEach(([column, count]) => {
    const percentage = (count / rows.length) * 100;
    if (count > 0) {
      qualityReport += `• ${column}: ${count} missing (${percentage.toFixed(1)}%)\n`;
    }
  });

  // Data completeness score
  const totalValues = headers.length * rows.length;
  const missingValues = Object.values(missingValueCounts).reduce((sum, count) => sum + count, 0);
  const completenessScore = ((totalValues - missingValues) / totalValues) * 100;
  
  qualityReport += `\nOverall Data Completeness: ${completenessScore.toFixed(1)}%\n`;
  
  if (completenessScore >= 95) {
    qualityReport += 'Quality Rating: Excellent - Very few missing values\n';
  } else if (completenessScore >= 85) {
    qualityReport += 'Quality Rating: Good - Some missing values present\n';
  } else if (completenessScore >= 70) {
    qualityReport += 'Quality Rating: Fair - Significant missing values that may affect analysis\n';
  } else {
    qualityReport += 'Quality Rating: Poor - High number of missing values. Analysis may be unreliable.\n';
  }

  return qualityReport;
}

function generateStatisticalInsights(data: ProcessedData): string {
  const { summary } = data;
  let insights = '';

  // Numerical insights
  if (summary.numericalColumns.length > 0) {
    insights += 'Numerical Data Insights:\n';
    summary.numericalColumns.forEach(column => {
      const stats = summary.columnStats[column];
      if (stats.mean && stats.stdDev) {
        const cv = (stats.stdDev / stats.mean) * 100; // Coefficient of variation
        insights += `• ${column}: `;
        if (cv < 15) {
          insights += 'Low variability (stable values)\n';
        } else if (cv < 30) {
          insights += 'Moderate variability\n';
        } else {
          insights += 'High variability (diverse values)\n';
        }
      }
    });
  }

  // Categorical insights
  if (summary.categoricalColumns.length > 0) {
    insights += '\nCategorical Data Insights:\n';
    summary.categoricalColumns.forEach(column => {
      const stats = summary.columnStats[column];
      if (stats.uniqueValues && stats.totalCount) {
        const diversity = (stats.uniqueValues / stats.totalCount) * 100;
        insights += `• ${column}: `;
        if (diversity < 10) {
          insights += 'Low diversity (few unique values)\n';
        } else if (diversity < 50) {
          insights += 'Moderate diversity\n';
        } else {
          insights += 'High diversity (many unique values)\n';
        }
      }
    });
  }

  return insights;
}

function analyzeCorrelations(data: ProcessedData): string {
  const { summary, rows } = data;
  let correlationReport = '';

  if (summary.numericalColumns.length >= 2) {
    correlationReport += 'Numerical Column Relationships:\n';
    
    // Simple correlation analysis for first few numerical columns
    const numCols = summary.numericalColumns.slice(0, 3); // Limit to first 3 for performance
    
    for (let i = 0; i < numCols.length; i++) {
      for (let j = i + 1; j < numCols.length; j++) {
        const col1 = numCols[i];
        const col2 = numCols[j];
        
        // Calculate basic correlation indicator
        const values1 = rows.map(row => Number(row[col1])).filter(v => !isNaN(v));
        const values2 = rows.map(row => Number(row[col2])).filter(v => !isNaN(v));
        
        if (values1.length > 0 && values2.length > 0) {
          const mean1 = values1.reduce((sum, v) => sum + v, 0) / values1.length;
          const mean2 = values2.reduce((sum, v) => sum + v, 0) / values2.length;
          
          correlationReport += `• ${col1} vs ${col2}: Data available for analysis\n`;
        }
      }
    }
  } else {
    correlationReport += 'Insufficient numerical columns for correlation analysis.\n';
  }

  return correlationReport;
}

function generateRecommendations(data: ProcessedData): string {
  const { summary, rows } = data;
  let recommendations = '';

  // Dataset size recommendations
  if (rows.length < 100) {
    recommendations += '• Consider collecting more data points for better statistical reliability\n';
  } else if (rows.length > 10000) {
    recommendations += '• Large dataset detected - consider sampling for faster analysis\n';
  }

  // Column recommendations
  if (summary.numericalColumns.length === 0) {
    recommendations += '• No numerical columns found - consider converting categorical data to numerical for statistical analysis\n';
  }

  if (summary.categoricalColumns.length === 0) {
    recommendations += '• No categorical columns found - consider grouping numerical data into categories for pattern analysis\n';
  }

  // Data quality recommendations
  const avgUniqueValues = summary.categoricalColumns.reduce((sum, col) => {
    return sum + (summary.columnStats[col].uniqueValues || 0);
  }, 0) / Math.max(summary.categoricalColumns.length, 1);

  if (avgUniqueValues > rows.length * 0.8) {
    recommendations += '• High number of unique categorical values - consider data consolidation\n';
  }

  if (recommendations === '') {
    recommendations = '• Dataset appears well-structured for analysis\n• Consider exploring visualizations for deeper insights\n';
  }

  return recommendations;
}

function generateDataSample(data: ProcessedData): string {
  const { headers, rows } = data;
  let sample = '';

  // Header row
  sample += headers.join(' | ') + '\n';
  sample += headers.map(h => '-'.repeat(h.length)).join('-|-') + '\n';

  // First 10 rows
  const sampleRows = rows.slice(0, 10);
  sampleRows.forEach(row => {
    const rowValues = headers.map(header => {
      const value = row[header];
      if (value === null || value === undefined) return 'NULL';
      const stringValue = String(value);
      if (stringValue.length > 30) {
        return stringValue.substring(0, 27) + '...';
      }
      return stringValue;
    });
    sample += rowValues.join(' | ') + '\n';
  });

  if (rows.length > 10) {
    sample += `\n... and ${rows.length - 10} more rows\n`;
  }

  return sample;
}

