function detectAnomalies(data: ProcessedData): string {
  const { summary, rows } = data;
  let anomalies = '';

  // Numerical outliers detection
  if (summary.numericalColumns.length > 0) {
    anomalies += 'Numerical Outlier Analysis:\n';
    
    summary.numericalColumns.forEach(column => {
      const stats = summary.columnStats[column];
      if (stats.mean && stats.stdDev && stats.min !== undefined && stats.max !== undefined) {
        const values = rows.map(row => Number(row[column])).filter(v => !isNaN(v));
        
        // Calculate potential outliers using IQR method
        values.sort((a, b) => a - b);
        const q1 = values[Math.floor(values.length * 0.25)];
        const q3 = values[Math.floor(values.length * 0.75)];
        const iqr = q3 - q1;
        const lowerBound = q1 - 1.5 * iqr;
        const upperBound = q3 + 1.5 * iqr;
        
        const outliers = values.filter(v => v < lowerBound || v > upperBound);
        const outlierPercentage = (outliers.length / values.length) * 100;
        
        anomalies += `• ${column}:\n`;
        if (outlierPercentage > 5) {
          anomalies += `  - Potential outliers detected: ${outliers.length} values (${outlierPercentage.toFixed(1)}%)\n`;
          anomalies += `  - Outlier range: Below ${lowerBound.toFixed(2)} or above ${upperBound.toFixed(2)}\n`;
        } else {
          anomalies += `  - Data appears clean with minimal outliers (${outlierPercentage.toFixed(1)}%)\n`;
        }
      }
    });
  }

  // Categorical anomalies
  if (summary.categoricalColumns.length > 0) {
    anomalies += '\nCategorical Data Anomalies:\n';
    
    summary.categoricalColumns.forEach(column => {
      const stats = summary.columnStats[column];
      if (stats.mostCommon && stats.uniqueValues && stats.totalCount) {
        const rareCategoriesCount = stats.mostCommon.filter(cat => cat.percentage < 1).length;
        
        anomalies += `• ${column}:\n`;
        if (rareCategoriesCount > 0) {
          anomalies += `  - Rare categories: ${rareCategoriesCount} categories with <1% frequency\n`;
          anomalies += `  - Consider grouping rare categories for analysis\n`;
        } else {
          anomalies += `  - No rare categories detected - good distribution\n`;
        }
      }
    });
  }

  return anomalies;
}

async function generateAIInsights(data: ProcessedData): Promise<string> {
  try {
    const apiKey = import.meta.env.VITE_GEMINI_API_KEY;
    
    if (!apiKey) {
      throw new Error('Missing API key for insights generation');
    }
    
    const genAI = new GoogleGenerativeAI(apiKey);
    const model = genAI.getGenerativeModel({ model: 'gemini-2.5-flash' });
    
    // Prepare data summary for AI analysis
    const dataSummary = {
      totalRows: data.summary.rowCount,
      totalColumns: data.summary.columnCount,
      numericalColumns: data.summary.numericalColumns,
      categoricalColumns: data.summary.categoricalColumns,
      columnStats: Object.fromEntries(
        Object.entries(data.summary.columnStats).map(([col, stats]: [string, any]) => [
          col,
          {
            type: data.summary.numericalColumns.includes(col) ? 'numerical' : 'categorical',
            ...(stats.mean !== undefined ? {
              min: stats.min,
              max: stats.max,
              mean: stats.mean,
              stdDev: stats.stdDev
            } : {
              uniqueValues: stats.uniqueValues,
              topValues: stats.mostCommon?.slice(0, 3)
            })
          }
        ])
      )
    };
    
    const prompt = `You are a world-class data analyst providing a report on the following dataset.

**Dataset Summary:**
\`\`\`json
${JSON.stringify(dataSummary, null, 2)}
\`\`\`

**Instructions:**
Generate a professional, insightful, and well-structured data analysis report in **Markdown format**.

The report should include the following sections:
- **\`## Executive Summary\`**: A high-level overview of the most critical findings and business implications.
- **\`## Key Findings & Patterns\`**: Detailed discoveries, trends, and significant data characteristics. Use bullet points.
- **\`## Business Intelligence Insights\`**: How the data relates to business performance, KPIs, and market behavior.
- **\`## Data Quality & Reliability Assessment\`**: An analysis of data completeness, potential issues, and its reliability for decision-making.
- **\`## Actionable Recommendations\`**: Specific, data-driven actions to take, areas for further investigation, and potential data collection improvements.

**Formatting Requirements:**
- Use Markdown for all formatting (e.g., \`##\` for H2, \`###\` for H3, \`**\` for bold, \`*\` for italics, \`*\` for list items, and \`\` for code snippets).
- Do NOT include a main title (\`# Report Title\`) in your response. The title is handled separately.
- Be concise yet comprehensive. Focus on insights that provide business value.`;

    const result = await model.generateContent(prompt);
    const response = await result.response;
    const insights = response.text();
    
    return insights;
    
  } catch (error) {
    console.error('Error generating AI insights:', error);
    return "### AI Insights Generation Failed\n\nWe were unable to generate AI-powered insights for your data at this time. This could be due to a network issue or a problem with the API key.\n\nPlease check your configuration and try again. The basic data summary is still available below.";
  }
}

